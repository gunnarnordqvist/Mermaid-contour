// Parser, text wrapping and quoting: pure functions, no browser. Run with `npm test`.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { parseContour, wrapToWidth } from '../src/mermaid-contour.mjs';

const U = 'level=0 rev=R1 reach=S mode=0';
const parse = (text) => parseContour(text);

test('every example parses and has the view its file name says', () => {
  const dir = new URL('../examples/', import.meta.url);
  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.mmd'));
  assert.ok(files.length >= 6);
  for (const file of files) {
    const model = parse(fs.readFileSync(new URL(file, dir), 'utf8'));
    const expected = file.includes('_year_') ? 'year' : file.includes('_compare_') ? 'compare' : file.match(/_(landscape|supply|decisions|evidence)_/)[1];
    assert.equal(model.view, expected, file);
    assert.ok(model.panels.every((p) => p.units.length > 0), file);
  }
});

test('absences are kept as absences', () => {
  const [u] = parse(`contour\n unit A "a" ${U}`).panels[0].units;
  assert.deepEqual([u.policy, u.tier, u.evidence, u.hosting, u.identity], ['none', 'T0', 'none', 'unknown', 'person']);
});

test('a planned unit is valid', () => {
  assert.equal(parse(`contour\n unit A "a" ${U} status=planned`).panels[0].units[0].status, 'planned');
});

test('unit ids are unique within a panel, not across panels, wherever the view line stands', () => {
  const two = `contour\n panel "a"\n unit X "x" ${U}\n panel "b"\n unit X "x" ${U}`;
  assert.equal(parse(`${two}\n view year`).view, 'year');
  assert.equal(parse(two).view, 'compare');
  assert.throws(() => parse(`contour\n unit A "a" ${U}\n unit A "b" ${U}`), /twice in this panel/);
});

test('a view without units is an empty view', () => {
  for (const view of ['landscape', 'supply', 'decisions', 'evidence']) assert.deepEqual(parse(`contour\n view ${view}`).panels, [{ name: '', units: [] }]);
});

test('names with quotes, backslashes and comment marks round-trip', () => {
  const awkward = 'Say "hi" \\ now %% done';
  const q = (s) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
  const m = parse(`contour-beta\n title ${q('Rate 5 %% of x')}\n panel ${q(awkward)}\n unit A ${q(awkward)} ${U}\n action ${q(awkward)} 1\n supplier s ${q(awkward)} ${q('here "now"')} role=model jurisdiction=EU`);
  assert.equal(m.title, 'Rate 5 %% of x');
  assert.equal(m.panels[0].name, awkward);
  assert.equal(m.panels[0].units[0].name, awkward);
  assert.equal(m.panels[0].units[0].actions[0][0], awkward);
  assert.equal(m.suppliers[0].label, awkward);
  assert.equal(m.suppliers[0].location, 'here "now"');
});

test('a comment is read after whitespace and never inside quotes', () => {
  const m = parse(`contour %% a comment\n%% a whole-line comment\n unit A "100%%" ${U} %% trailing\n`);
  assert.equal(m.panels[0].units[0].name, '100%%');
});

const rejects = [
  ['flowchart LR', 'expected "contour"'],
  [`contour\n unit A "a" level=5 rev=R1 reach=S mode=0`, 'level=5'],
  [`contour\n unit A "a" level=0 rev=R9 reach=S mode=0`, 'rev=R9'],
  [`contour\n unit A "a" level=0 rev=R1 reach=S`, 'lacks mode'],
  [`contour\n unit A "a" ${U} colour=red`, 'unknown attribute colour'],
  [`contour\n unit A "a" ${U} toString=1`, 'unknown attribute toString'],
  [`contour\n unit A "a" level=0x1 rev=R1 reach=S mode=0`, 'level=0x1'],
  [`contour\n unit A "a" level=1.0 rev=R1 reach=S mode=0`, 'level=1.0'],
  [`contour\n unit A "a"level=1 rev=R1 reach=S mode=0`, 'cannot read'],
  [`contour\n unit A "a" ${U}\n panel "p"`, 'belong to no panel'],
  ['contour\n view nonsense', 'view must be one of'],
  ['contour\n view compare\n panel "A"', 'needs two panels'],
  ['contour\n panel "a"\n panel "b"\n panel "c"', 'at most two panels'],
  ['contour\n action "x" 1', 'belongs under a unit'],
  [`contour\n unit A "a" ${U}\n action "x" 5`, 'action level must be 0 to 4'],
];
for (const [text, message] of rejects) {
  test(`rejects: ${message}`, () => assert.throws(() => parse(text), (e) => e.message.includes(message)));
}

test('the id __proto__ is an ordinary id', () => {
  assert.equal(parse(`contour\n unit __proto__ "n" ${U}`).panels[0].units[0].id, '__proto__');
});

// textwrap.wrap of Python 3.12 (the toolchain of the book) on 92 strings, as generated by Python itself
const golden = JSON.parse(fs.readFileSync(new URL('./golden-wrap.json', import.meta.url), 'utf8'));
test(`wrapToWidth equals Python's textwrap on ${golden.length} strings`, () => {
  const bad = golden.filter(({ text, chars, lines }) => {
    const got = wrapToWidth(text, chars * 0.07 + 0.001); // width in inches; 0.07 in per character
    return JSON.stringify(got) !== JSON.stringify(lines);
  });
  assert.deepEqual(bad.slice(0, 3), []);
});
